export class HttpError extends Error {
  status: number;
  code: string;
  constructor(status: number, code: string, message?: string) {
    super(message ?? code);
    this.status = status;
    this.code = code;
  }
}

export const bad = (message: string, code = 'bad_request') => new HttpError(400, code, message);
export const forbidden = (message = 'You do not have permission to do this.') =>
  new HttpError(403, 'forbidden', message);
export const notFound = (message = 'Not found.') => new HttpError(404, 'not_found', message);
export const conflict = (code: string, message: string) => new HttpError(409, code, message);

export function json(data: unknown, status = 200, headers: Record<string, string> = {}): Response {
  return new Response(JSON.stringify(data), {
    status,
    headers: {
      'content-type': 'application/json; charset=utf-8',
      'cache-control': 'no-store',
      'x-content-type-options': 'nosniff',
      ...headers,
    },
  });
}

export function reqStr(v: unknown, name: string, min: number, max: number): string {
  if (typeof v !== 'string') throw bad(`${name} is required.`);
  const s = v.trim();
  if (s.length < min || s.length > max) {
    throw bad(`${name} must be between ${min} and ${max} characters.`);
  }
  return s;
}

export function reqInt(v: unknown, name: string, min: number, max: number): number {
  if (typeof v !== 'number' || !Number.isInteger(v) || v < min || v > max) {
    throw bad(`${name} must be an integer between ${min} and ${max}.`);
  }
  return v;
}

export function reqIdList(v: unknown, name: string, max: number): number[] {
  if (!Array.isArray(v) || v.length === 0 || v.length > max) {
    throw bad(`${name} must contain between 1 and ${max} IDs.`);
  }
  const ids = v.map((x) => reqInt(x, name, 1, Number.MAX_SAFE_INTEGER));
  return [...new Set(ids)];
}

/** Idempotency keys are generated by the client once per form submission. */
export function reqKey(v: unknown): string {
  if (typeof v !== 'string' || !/^[A-Za-z0-9_-]{8,64}$/.test(v)) {
    throw bad('A valid submission key is required.');
  }
  return v;
}

/** Query-string helper. */
export function qInt(url: URL, name: string, def: number, min: number, max: number): number {
  const raw = url.searchParams.get(name);
  if (raw === null || raw === '') return def;
  const n = Number(raw);
  if (!Number.isInteger(n) || n < min || n > max) throw bad(`${name} is invalid.`);
  return n;
}

export const chunk = <T>(arr: T[], size: number): T[][] => {
  const out: T[][] = [];
  for (let i = 0; i < arr.length; i += size) out.push(arr.slice(i, i + size));
  return out;
};

export const isUniqueError = (e: unknown) =>
  /UNIQUE constraint failed/i.test(String((e as Error)?.message ?? e));
