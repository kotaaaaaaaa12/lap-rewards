'use strict';
// Minimal i18n. The English text itself is the key: t('Sign in') returns 'Sign in' in English
// and the Japanese entry in JA otherwise. A missing translation falls back to English,
// so a forgotten string never breaks the UI (test/i18n.test.ts checks coverage).
// Placeholders look like {name}; pass values as t('Hello {name}', { name }).

const LANGS = { en: 'English', ja: '日本語' };
const LANG_TAGS = { en: 'en', ja: 'ja-JP' };
let lang = 'en';

function detectLang() {
  try {
    const saved = localStorage.getItem('lap_lang');
    if (saved && LANGS[saved]) return saved;
  } catch { /* storage unavailable */ }
  return String(navigator.language || 'en').toLowerCase().startsWith('ja') ? 'ja' : 'en';
}

function setLang(next) {
  lang = LANGS[next] ? next : 'en';
  try { localStorage.setItem('lap_lang', lang); } catch { /* ignore */ }
  document.documentElement.lang = LANG_TAGS[lang];
}

