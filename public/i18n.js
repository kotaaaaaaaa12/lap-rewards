function t(key, params) {
  let s = key;
  if (lang === 'ja') {
    if (Object.prototype.hasOwnProperty.call(JA, key)) {
      s = JA[key];
    } else {
      for (const [re, tpl] of PATTERNS) {
        const m = re.exec(key);
        if (m) { s = tpl.replace(/\{(\d)\}/g, (_x, i) => t(m[Number(i) + 1])); break; }
      }
    }
  }
  if (!params) return s;
  return s.replace(/\{(\w+)\}/g, (_m, k) => (Object.prototype.hasOwnProperty.call(params, k) ? String(params[k]) : '{' + k + '}'));
}

/** Picks the singular or plural English key (Japanese entries are identical for both). */
const tn = (n, one, other, params) => t(n === 1 ? one : other, Object.assign({ n }, params));

